void print_logo() {
  int line = 10;
  int column = 10;

  for(int i = 0; i < 16 * 113; i++) {
    for(int b = 0; b < 8; b++) {
      if((logo[i] >> (7 - b)) & 0x01) {
        fb_putpixel(column, line, FB_LIGHT_WHITE);
      }
      column++;
    };

    if(i % 16 == 0) {
      line++;
      column = 10;
    } else {
      column++;
    }
  }

  gotoxy(0, 7);
}